package com.xspaceagi.system.spec.license;

/**
 * 授权码校验结论（分档，不做二值化）。
 */
public enum LicenseStatus {

    /** 未配置授权串 —— 社区版形态，一切照常 */
    ABSENT,

    /** 验签通过且在有效期内 */
    VALID,

    /** 已过期，但仍在宽限期内：可用 + 全端告警 */
    GRACE,

    /** 已过期且超出宽限期 */
    EXPIRED,

    /** 格式不合法 / 验签失败 / 旧格式已停用 */
    INVALID,

    /**
     * 验签通过，但本机不在授权码绑定的设备范围内（拷到别的机器 / 换了机器）。
     *
     * <p>与 {@link #INVALID} 分开是为了排查时一眼能分清「串被改过」和「串是真的、只是不这台机器」。
     * 二者的放行结论相同：不放行，且**不采信载荷**（否则把授权串拷到任意机器就能改产品版本）。
     */
    MISMATCH
}
